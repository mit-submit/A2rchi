#!/usr/bin/env python3
"""Generate eval configs for the submit75 CHEP matrix.

Writes 4 per (model × thinking_mode) combination:
    - optimized-tools  (CMSCompOpsAgent full tools)
    - no-tools         (CMSCompOpsAgent RAG/metadata only)
    - rag-only         (QAPipeline)
    - bare-llm         (BareLLMPipeline)

Services sections are identical within a batch (required for multi-config
`archi evaluate` deployments to share one ingestion). The only differences
allowed are inside `services.benchmarking` (name, agent_class, agent_md_file)
and the bare-llm data_manager stanza (which disables all sources because
the bare LLM path doesn't retrieve).

Usage:

    python scripts/submit75/generate_eval_configs.py
    python scripts/submit75/generate_eval_configs.py --only gemma4-26b --thinking off
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import List

REPO_ROOT = Path(__file__).resolve().parents[2]
CONFIG_DIR = REPO_ROOT / "configs" / "submit75"

# ─────────────────────────────────────────────────────────────────────
# Model definitions
# ─────────────────────────────────────────────────────────────────────

MODELS = [
    # (slug, ollama_tag)
    ("gemma4-26b", "gemma4:26b"),
    ("qwen3.5-27b", "qwen3.5:27b"),
    ("qwen3.5-122b-a10b", "qwen3.5:122b-a10b"),
]

THINKING_MODES = ["on", "off"]

CONDITIONS = [
    # (condition_slug, agent_class, agent_md_file, disable_data_sources, is_agent)
    (
        "optimized-tools",
        "CMSCompOpsAgent",
        "examples/agents/cms-comp-ops.md",
        False,
        True,
    ),
    (
        "no-tools",
        "CMSCompOpsAgent",
        "examples/agents/cms-comp-ops-no-live-data.md",
        False,
        True,
    ),
    (
        "rag-only",
        "QAPipeline",
        "examples/agents/cms-comp-ops.md",
        False,
        False,
    ),
    (
        "bare-llm",
        "BareLLMPipeline",
        "examples/agents/cms-comp-ops.md",
        True,
        False,
    ),
]

NUM_CTX = 65536
NUM_PREDICT = 4096
OLLAMA_URL = "http://localhost:11434"
POSTGRES_PORT = 5436
DATA_MANAGER_PORT = 7871
QUERIES_PATH = "configs/submit75/curated_questions_categorized.json"


def render_config(
    *,
    condition: str,
    agent_class: str,
    agent_md_file: str,
    disable_data_sources: bool,
    is_agent: bool,
    model_slug: str,
    model_tag: str,
    thinking_mode: str,
) -> str:
    """Return the full YAML text for one config."""
    name = f"{condition}-{model_slug}-thinking-{thinking_mode}"
    parallel_workers = {
        "gemma4-26b": 4,
        "qwen3.5-27b": 2,
        "qwen3.5-122b-a10b": 1,
    }[model_slug]
    reasoning_value = "true" if thinking_mode == "on" else "false"

    header = (
        f"# CHEP eval config — {condition} × {model_tag} × thinking-{thinking_mode}\n"
        f"# Host: submit75.mit.edu (Ollama on 11434, Postgres eval on 5436)\n"
        f"# Auto-generated by scripts/submit75/generate_eval_configs.py\n"
        f"# Multi-config compatible: services section matches other {condition} variants\n"
        f"# in the same (model, thinking) batch.\n"
    )

    benchmarking = f"""
services:
  benchmarking:
    name: {name}
    parallel_workers: {parallel_workers}
    agent_class: {agent_class}
    agent_md_file: {agent_md_file}
    provider: local
    model: "{model_tag}"
    ollama_url: {OLLAMA_URL}
    queries_path: {QUERIES_PATH}
    out_dir: bench_out
    modes: []
"""

    # chat_app section — IDENTICAL across all 4 conditions within a batch so
    # that `archi evaluate --config a,b,c,d` works (multi-config mode).
    chat_app = f"""  chat_app:
    skills_dir: examples/skills
    tools:
      monit:
        url: "https://monit-grafana.cern.ch/api/datasources/proxy/9269/_msearch"
        rucio:
          url: "https://monit-grafana.cern.ch/api/datasources/proxy/9269/_msearch"
        condor:
          url: "https://monit-grafana.cern.ch/api/datasources/proxy/8787/_msearch"
    providers:
      local:
        base_url: {OLLAMA_URL}
        enabled: true
        mode: ollama
        options:
          num_predict: {NUM_PREDICT}
          num_ctx: {NUM_CTX}
          reasoning: {reasoning_value}
"""

    services_rest = f"""  postgres:
    port: {POSTGRES_PORT}
    user: archi
    database: archi-db
  data_manager:
    hostname: localhost
    port: {DATA_MANAGER_PORT}
"""

    if disable_data_sources:
        data_manager = """
data_manager:
  sources:
    jira:
      enabled: false
    links:
      enabled: false
    redmine:
      enabled: false
  embedding_name: HuggingFaceEmbeddings
  collection_name: default_collection
  embedding_class_map:
    HuggingFaceEmbeddings:
      class: HuggingFaceEmbeddings
      kwargs:
        model_name: sentence-transformers/all-MiniLM-L6-v2
        model_kwargs:
          device: cpu
        encode_kwargs:
          normalize_embeddings: true
      similarity_score_reference: 10
"""
    else:
        data_manager = """
data_manager:
  sources:
    jira:
      enabled: true
      url: https://its.cern.ch/jira/
      projects:
        - "CMSTZ"
        - "CMSPROD"
        - "CMSTRANSF"
        - "CMSDM"
        - "PRCAMPAIGNS"
        - "CMSMONIT"
        - "CMSVOC"
      anonymize_data: true
    links:
      enabled: true
      base_source_depth: 2
      input_lists:
        - configs/submit75/public_docs.list
        - configs/submit75/git_repos.list
    redmine:
      enabled: false
  embedding_name: HuggingFaceEmbeddings
  collection_name: default_collection
  embedding_class_map:
    HuggingFaceEmbeddings:
      class: HuggingFaceEmbeddings
      kwargs:
        model_name: sentence-transformers/all-MiniLM-L6-v2
        model_kwargs:
          device: cpu
        encode_kwargs:
          normalize_embeddings: true
      similarity_score_reference: 10
    OpenAIEmbeddings:
      class: OpenAIEmbeddings
      kwargs:
        model: text-embedding-3-small
      similarity_score_reference: 10
"""

    return header + "\nname: eval-curated\n" + benchmarking + chat_app + services_rest + data_manager


def generate(
    out_dir: Path,
    *,
    only_model: str | None = None,
    only_thinking: str | None = None,
) -> List[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written: List[Path] = []
    for model_slug, model_tag in MODELS:
        if only_model and model_slug != only_model:
            continue
        for thinking_mode in THINKING_MODES:
            if only_thinking and thinking_mode != only_thinking:
                continue
            for cond_slug, agent_class, agent_md_file, disable, is_agent in CONDITIONS:
                content = render_config(
                    condition=cond_slug,
                    agent_class=agent_class,
                    agent_md_file=agent_md_file,
                    disable_data_sources=disable,
                    is_agent=is_agent,
                    model_slug=model_slug,
                    model_tag=model_tag,
                    thinking_mode=thinking_mode,
                )
                filename = f"eval-{cond_slug}-{model_slug}-thinking-{thinking_mode}.yaml"
                path = out_dir / filename
                path.write_text(content)
                written.append(path)
    return written


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out-dir", type=Path, default=CONFIG_DIR)
    parser.add_argument("--only-model", choices=[m[0] for m in MODELS])
    parser.add_argument("--only-thinking", choices=THINKING_MODES)
    parser.add_argument("--dry-run", action="store_true", help="Print filenames only")
    args = parser.parse_args()

    if args.dry_run:
        count = 0
        for model_slug, _ in MODELS:
            if args.only_model and model_slug != args.only_model:
                continue
            for thinking_mode in THINKING_MODES:
                if args.only_thinking and thinking_mode != args.only_thinking:
                    continue
                for cond_slug, _, _, _, _ in CONDITIONS:
                    print(f"eval-{cond_slug}-{model_slug}-thinking-{thinking_mode}.yaml")
                    count += 1
        print(f"\n{count} configs would be written to {args.out_dir}")
        return 0

    written = generate(args.out_dir, only_model=args.only_model, only_thinking=args.only_thinking)
    print(f"Wrote {len(written)} configs to {args.out_dir}")
    for p in written:
        print(f"  {p.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
